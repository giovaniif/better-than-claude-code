import { describe, expect, test } from "bun:test";
import { historyEvents, lastModel, sessionRow } from "./history";

const user = (content: unknown, extra = {}) => ({ type: "user", uuid: "u", session_id: "s", parent_tool_use_id: null, parent_agent_id: null, message: { role: "user", content }, ...extra });
const assistant = (content: unknown[], extra = {}) => ({ type: "assistant", uuid: "a", session_id: "s", parent_tool_use_id: null, parent_agent_id: null, message: { role: "assistant", content }, ...extra });

describe("sessionRow", () => {
  test("prefers the custom title, then the summary, then the first prompt", () => {
    expect(sessionRow({ sessionId: "x", summary: "sum", customTitle: "mine", firstPrompt: "fp", lastModified: 5, cwd: "/a", gitBranch: "b", createdAt: 1 })).toEqual({ sessionId: "x", title: "mine", cwd: "/a", gitBranch: "b", lastModified: 5, createdAt: 1 });
    expect(sessionRow({ sessionId: "x", summary: "", firstPrompt: "fp", lastModified: 5 }).title).toBe("fp");
    expect(sessionRow({ sessionId: "x", summary: "", lastModified: 5 }).title).toBe("Untitled Claude Code session");
  });
});

describe("historyEvents", () => {
  test("turns prompts, answers and tool calls into yardd events, one turn per prompt", () => {
    const events = historyEvents(
      [
        user("Fix the login redirect"),
        assistant([{ type: "thinking", thinking: "Look at login first" }, { type: "text", text: "Reading it." }, { type: "tool_use", id: "t1", name: "Read", input: { file_path: "/repo/src/login.ts" } }]),
        user([{ type: "tool_result", tool_use_id: "t1", content: "export function login() {}" }]),
        assistant([{ type: "text", text: "Fixed." }]),
        user([{ type: "text", text: "Thanks" }]),
        assistant([{ type: "text", text: "Anytime." }]),
      ],
      "/repo",
    );
    expect(events.map((e) => e.type)).toEqual([
      "user_message",
      "turn_started",
      "reasoning",
      "assistant_message",
      "tool_started",
      "tool_completed",
      "assistant_message",
      "turn_completed",
      "user_message",
      "turn_started",
      "assistant_message",
      "turn_completed",
    ]);
    expect(events[0]).toEqual({ type: "user_message", text: "Fix the login redirect" });
    expect(events[4]).toMatchObject({ type: "tool_started", itemId: "t1", kind: "read", title: "Read", detail: "src/login.ts" });
    expect(events[5]).toMatchObject({ type: "tool_completed", itemId: "t1", ok: true });
    expect(events[7]).toEqual({ type: "turn_completed", status: "completed" });
  });

  test("edits keep their diff", () => {
    const events = historyEvents([user("edit it"), assistant([{ type: "tool_use", id: "e1", name: "Edit", input: { file_path: "/r/a.ts", old_string: "a", new_string: "b" } }])], "/r");
    expect(events.find((e) => e.type === "file_change")).toMatchObject({ files: [{ path: "a.ts", diff: "-a\n+b", kind: "update" }] });
  });

  test("Claude Code's own bookkeeping and subagent chatter stay out", () => {
    const events = historyEvents(
      [
        user("<command-name>/clear</command-name>"),
        user("Caveat: The messages below were generated by the user while running local commands."),
        user("<local-command-stdout></local-command-stdout>"),
        user("real prompt"),
        assistant([{ type: "text", text: "inside a subagent" }], { parent_tool_use_id: "t9" }),
        assistant([{ type: "text", text: "answer" }]),
        { type: "system", uuid: "x", session_id: "s", parent_tool_use_id: null, parent_agent_id: null, message: {} },
      ],
      "/r",
    );
    expect(events.filter((e) => e.type === "user_message").map((e) => e.text)).toEqual(["real prompt"]);
    expect(events.filter((e) => e.type === "assistant_message").map((e) => e.text)).toEqual(["answer"]);
  });

  test("a failed tool result is not ok, and item ids never repeat", () => {
    const events = historyEvents(
      [user("go"), assistant([{ type: "text", text: "one" }, { type: "tool_use", id: "b1", name: "Bash", input: { command: "false" } }]), user([{ type: "tool_result", tool_use_id: "b1", is_error: true, content: [{ type: "text", text: "exit 1" }] }]), assistant([{ type: "text", text: "two" }])],
      "/r",
    );
    expect(events.find((e) => e.type === "tool_completed")).toMatchObject({ ok: false, output: "exit 1" });
    const ids = events.filter((e) => e.itemId).map((e) => e.itemId);
    expect(new Set(ids.filter((i) => i !== "b1")).size).toBe(ids.filter((i) => i !== "b1").length);
  });
});

describe("lastModel", () => {
  test("the last main-thread answer's model, skipping synthetic answers and subagents", () => {
    const a = (model: string, extra = {}) => ({ type: "assistant", parent_tool_use_id: null, message: { role: "assistant", model, content: [] }, ...extra });
    expect(lastModel([a("claude-opus-5-5"), a("claude-haiku-5-5-20261001"), a("<synthetic>"), a("claude-sonnet-5-5", { parent_tool_use_id: "t1" })])).toBe("claude-haiku-5-5-20261001");
    expect(lastModel([{ type: "user", message: { content: "hi" } }])).toBeNull();
  });
});
